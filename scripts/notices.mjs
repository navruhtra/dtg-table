// @ts-check
// Third-party notices and file hashes, generated from the pins in vendor-pins.mjs. No license text is typed by hand.
//   node scripts/notices.mjs            write THIRD-PARTY-NOTICES.md (license texts from .cache/node_modules and the
//                                       engine's LICENSE) and src/vendor.sha256
//   node scripts/notices.mjs --check    fail if either file is out of date, or a file in src/vendor/ differs from its pin
// src/vendor.sha256 sits next to vendor/ and is in sha256sum format, so `sha256sum -c vendor.sha256` in src/ checks it
// without Node. After a changed pin: node scripts/fetch-vendor.mjs, then node scripts/notices.mjs, and commit both files.
import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { PACKAGES, ENGINE, NO_LICENSE_FILE } from "./vendor-pins.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), ".."), src = join(root, "src"), MANIFEST = "vendor.sha256", NOTICES = "THIRD-PARTY-NOTICES.md";
const sha256 = f => createHash("sha256").update(readFileSync(f)).digest("hex");
/** Every file under dir, as paths relative to base, sorted. */
const walk = (dir, base) => readdirSync(dir).sort().flatMap(n => { const f = join(dir, n); return statSync(f).isDirectory() ? walk(f, base) : [relative(base, f).split("\\").join("/")]; });

/** The manifest text for the files in <dir>/vendor. */
function manifestText(dir) { return walk(join(dir, "vendor"), dir).map(p => `${sha256(join(dir, p))}  ${p}`).join("\n") + "\n"; }
/** @returns {Map<string, string>} path → SHA-256, from vendor.sha256 */
export function readManifest(dir = src) {
  return new Map(readFileSync(join(dir, MANIFEST), "utf8").trim().split("\n").map(l => { const [h, p] = l.split(/\s+/); return [p, h]; }));
}

/**
 * Check the files under <dir>/vendor against the pins in <dir>/vendor.sha256.
 * @returns {string[]} one line per problem; empty when everything matches
 */
export function verifyVendor({ dir = src } = {}) {
  const pins = readManifest(dir), bad = [];
  const have = existsSync(join(dir, "vendor")) ? walk(join(dir, "vendor"), dir) : [];
  for (const f of have) if (!pins.has(f)) bad.push(`${f}: not pinned in vendor.sha256 (add it to scripts/vendor-pins.mjs, then run node scripts/notices.mjs)`);
  for (const [p, h] of pins) {
    const f = join(dir, p);
    if (!existsSync(f)) { bad.push(`${p}: missing (run npm run setup)`); continue; }
    const got = sha256(f);
    if (got !== h) bad.push(`${p}: SHA-256 ${got.slice(0, 12)}… is not the pinned ${h.slice(0, 12)}…`);
  }
  return bad;
}

/* ───────────── THIRD-PARTY-NOTICES.md ───────────── */
const LICENSE_FILE = /^(licen[cs]e|copying|notice)(\.(md|txt|markdown))?$/i;
function licenseText(dir) {
  const f = readdirSync(dir).filter(n => LICENSE_FILE.test(n)).sort()[0];
  return f ? readFileSync(join(dir, f), "utf8").replace(/\r\n/g, "\n").trim() : null;
}
const repoUrl = pj => { const r = typeof pj.repository === "string" ? pj.repository : pj.repository && pj.repository.url; return r ? r.replace(/^git\+/, "").replace(/\.git$/, "").replace(/^git:\/\//, "https://").replace(/^github:/, "https://github.com/") : pj.homepage || ""; };
/** Packages esbuild put into a bundle, from its metafile: name → folder under node_modules. */
function bundled(nm, meta) {
  const names = new Set();
  for (const p of Object.keys(JSON.parse(readFileSync(meta, "utf8")).inputs)) { const m = p.match(/node_modules\/((?:@[^/]+\/)?[^/]+)\//); if (m) names.add(m[1]); }
  return [...names].sort().map(n => join(nm, n));
}

function noticesText() {
  const nm = join(root, ".cache/node_modules"), meta = join(root, ".cache/quickhull.meta.json"), lic = join(src, "vendor", ENGINE.files.LICENSE);
  if (!existsSync(nm) || !existsSync(meta) || !existsSync(lic)) throw new Error(".cache/node_modules, .cache/quickhull.meta.json or the engine's LICENSE is missing: run npm run setup first");
  const out = ["# Third-party notices", "", "Generated by `node scripts/notices.mjs` from the pins in scripts/vendor-pins.mjs",
    "and the files scripts/fetch-vendor.mjs downloads. Do not edit by hand. The",
    "SHA-256 of every downloaded file is in src/vendor.sha256. NOTICE says what each",
    "one is used for.", ""];
  const files = to => to.map(f => `src/vendor/${f}`).join(", ");
  const section = (title, version, license, source, where, text) => {
    out.push(`## ${title} ${version}`, "", `- License: ${license}`, `- Source: ${source}`, `- Files: ${where}`, "");
    if (text.startsWith("```")) out.push(text, ""); else out.push("```text", text, "```", "");
  };
  section(ENGINE.name, `(commit ${ENGINE.commit.slice(0, 7)})`, ENGINE.license, `https://github.com/${ENGINE.repo}/tree/${ENGINE.commit}`, files(Object.values(ENGINE.files)), readFileSync(lic, "utf8").replace(/\r\n/g, "\n").trim());
  for (const p of PACKAGES) {
    if (p.tool) continue;
    const dir = join(nm, p.pkg), pj = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
    if (pj.version !== p.version) throw new Error(`${p.pkg}: installed ${pj.version}, pinned ${p.version}: run npm run setup`);
    const dirs = p.bundle ? bundled(nm, meta) : [dir];
    for (const d of dirs) {
      const q = JSON.parse(readFileSync(join(d, "package.json"), "utf8")), declared = typeof q.license === "object" && q.license ? q.license.type : q.license;
      let text = licenseText(d); if (!text && NO_LICENSE_FILE[q.name]) text = NO_LICENSE_FILE[q.name];
      if (!text) throw new Error(`${q.name}: no license file in the package: add a NO_LICENSE_FILE note in vendor-pins.mjs`);
      if (!licenseText(d)) { out.push(`## ${q.name} ${q.version}`, "", `- License: ${declared}`, `- Source: ${repoUrl(q)}`, `- Files: src/vendor/${p.bundle} (bundled)`, "", text, ""); continue; }
      section(q.name, q.version, declared, repoUrl(q), p.bundle ? `src/vendor/${p.bundle} (bundled)` : files(Object.values(p.files)), text);
    }
  }
  return out.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (!process.argv.includes("--check")) {
    writeFileSync(join(src, MANIFEST), manifestText(src)); writeFileSync(join(root, NOTICES), noticesText());
    console.log(`Wrote ${NOTICES} and src/${MANIFEST}`);
  } else {
    const bad = verifyVendor();
    if (readFileSync(join(root, NOTICES), "utf8") !== noticesText()) bad.push(`${NOTICES} is out of date: run node scripts/notices.mjs and commit it`);
    for (const l of bad) console.log("FAIL", l);
    console.log(bad.length ? `${bad.length} FAILED` : `notices and vendor hashes match (${readManifest().size} pinned files)`);
    process.exitCode = bad.length ? 1 : 0;
  }
}
